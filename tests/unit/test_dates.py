import pytest

from integrations.dates import start_time


@pytest.mark.parametrize(
    "label,anchor,expected",
    [
        ("Завтра в 12:00", "2026-10-04T20:00:00+00:00", "2026-10-05T09:00:00+00:00"),
        ("Сегодня 12:00", "2026-10-04T22:00:00+00:00", "2026-10-05T09:00:00+00:00"),
        ("Начало через 2 дня 12 часов 24 мин.", "2026-10-04T20:00:00+00:00", "2026-10-07T08:24:00+00:00"),
        ("08.10.26 12:00", "2026-10-04T20:00:00+00:00", "2026-10-08T09:00:00+00:00"),
        ("01 янв 12:00", "2026-12-31T20:00:00+00:00", "2027-01-01T09:00:00+00:00"),
        ("05 окт 12:00", "2026-10-04T20:00:00+00:00", "2026-10-05T09:00:00+00:00"),
        ("Начало через 12 часов", "2026-10-04T20:00:00+00:00", None),
        ("12:00", "2026-10-04T20:00:00+00:00", None),
        ("Сегодня 12:00", None, None),
        ("Сегодня 12:00", "2026-10-04T20:00:00", None),
    ],
)
def test_line_dates(label, anchor, expected):
    assert start_time(label, anchor) == expected
